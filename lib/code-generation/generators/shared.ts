export function extractModulesFromIdea(ideaText: string): string[] {
  const keywords: Record<string, string[]> = {
    technicians: ["técnico", "technician", "campo", "field"],
    clients: ["cliente", "client", "customer"],
    work_orders: ["incidencia", "orden", "work order", "ticket", "servicio"],
    routes: ["ruta", "route", "dispatch"],
    inventory: ["inventario", "inventory", "stock", "almacén"],
    billing: ["factura", "billing", "invoice", "cobro"],
    dashboard: ["dashboard", "panel", "métrica"],
    auth: ["auth", "login", "usuario", "rol"],
  };

  const lower = ideaText.toLowerCase();
  const modules: string[] = [];
  for (const [mod, words] of Object.entries(keywords)) {
    if (words.some((w) => lower.includes(w))) modules.push(mod);
  }
  if (modules.length === 0) modules.push("dashboard", "auth");
  return modules;
}

export function buildPackageJson(
  slug: string,
  manifest: TemplateManifest,
  deps: CodeDependency[]
): string {
  return JSON.stringify(
    {
      name: slug,
      version: "0.1.0",
      private: true,
      scripts: manifest.scripts,
      dependencies: dependenciesToPackageJson(deps),
      devDependencies: devDependenciesToPackageJson(deps),
    },
    null,
    2
  );
}

export function buildTsConfig(): string {
  return JSON.stringify(
    {
      compilerOptions: {
        target: "ES2017",
        lib: ["dom", "dom.iterable", "esnext"],
        allowJs: true,
        skipLibCheck: true,
        strict: true,
        noEmit: true,
        esModuleInterop: true,
        module: "esnext",
        moduleResolution: "bundler",
        resolveJsonModule: true,
        isolatedModules: true,
        jsx: "preserve",
        incremental: true,
        paths: { "@/*": ["./*"] },
      },
      include: ["**/*.ts", "**/*.tsx"],
      exclude: ["node_modules"],
    },
    null,
    2
  );
}

